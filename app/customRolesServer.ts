import { getDatabase, type PostgresDatabase } from "../db/client";
import { CustomRoleError, customRoleNameKey, inferCustomRoleBaseRole, normalizeCustomRoleInput, normalizeCustomRoleName, normalizeCustomRolePermissions, type CustomRole, type CustomRoleInput } from "./customRoles.ts";

type Executor = Pick<PostgresDatabase, "prepare">;
const schemaTasks = new WeakMap<PostgresDatabase, Promise<void>>();

export async function ensureCustomRolesSchema(db?: PostgresDatabase) {
  if (process.env.NODE_ENV === "production" && process.env.DATABASE_RUNTIME_BOOTSTRAP !== "true") return;
  const database = db ?? getDatabase();
  let task = schemaTasks.get(database);
  if (!task) {
    task = database.transaction(async tx => {
      await tx.prepare(`CREATE TABLE IF NOT EXISTS custom_roles (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL, name_key TEXT NOT NULL UNIQUE,
        base_role TEXT NOT NULL CHECK (base_role IN ('engineer', 'viewer')),
        permissions JSONB NOT NULL CHECK (jsonb_typeof(permissions) = 'object'),
        revision INTEGER NOT NULL DEFAULT 1 CHECK (revision > 0),
        active INTEGER NOT NULL DEFAULT 1 CHECK (active IN (0, 1)),
        created_by_user_id INTEGER REFERENCES app_users(id) ON DELETE SET NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
        updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
      )`).run();
      await tx.prepare("ALTER TABLE app_users ADD COLUMN IF NOT EXISTS custom_role_id INTEGER REFERENCES custom_roles(id) ON DELETE RESTRICT").run();
      await tx.prepare("CREATE INDEX IF NOT EXISTS idx_app_users_custom_role ON app_users(custom_role_id)").run();
    }).catch(error => { schemaTasks.delete(database); throw error; });
    schemaTasks.set(database, task);
  }
  await task;
}

type CustomRoleRow = { id: number; name: string; baseRole: string; permissions: unknown; revision: number };
function customRoleFromRow(row: CustomRoleRow): CustomRole | null {
  try {
    const permissions = normalizeCustomRolePermissions(typeof row.permissions === "string" ? JSON.parse(row.permissions) : row.permissions);
    const baseRole = inferCustomRoleBaseRole(permissions);
    if (baseRole !== row.baseRole || !Number.isSafeInteger(row.id) || row.id < 1 || !Number.isSafeInteger(row.revision) || row.revision < 1) return null;
    return { id: row.id, name: normalizeCustomRoleName(row.name), baseRole, permissions, revision: row.revision };
  } catch { return null; }
}
const columns = "id, name, base_role AS baseRole, permissions, revision";

export async function listCustomRoles(executor: Executor = getDatabase()): Promise<CustomRole[]> {
  await ensureCustomRolesSchema();
  const result = await executor.prepare(`SELECT ${columns} FROM custom_roles WHERE active = 1 ORDER BY name_key, id`).all<CustomRoleRow>();
  return result.results.flatMap(row => { const role = customRoleFromRow(row); return role ? [role] : []; });
}

export async function loadCustomRole(id: number, executor: Executor = getDatabase()): Promise<CustomRole | null> {
  if (!Number.isSafeInteger(id) || id < 1 || id > 2147483647) return null;
  await ensureCustomRolesSchema();
  const row = await executor.prepare(`SELECT ${columns} FROM custom_roles WHERE id = ? AND active = 1`).bind(id).first<CustomRoleRow>();
  return row ? customRoleFromRow(row) : null;
}

export async function createCustomRole(input: CustomRoleInput, actorId: number, executor: Executor = getDatabase()): Promise<CustomRole> {
  const normalized = normalizeCustomRoleInput(input);
  await ensureCustomRolesSchema();
  try {
    const row = await executor.prepare(`INSERT INTO custom_roles(name, name_key, base_role, permissions, created_by_user_id)
      VALUES (?, ?, ?, ?::jsonb, ?) RETURNING ${columns}`)
      .bind(normalized.name, customRoleNameKey(normalized.name), normalized.baseRole, JSON.stringify(normalized.permissions), actorId).first<CustomRoleRow>();
    const role = row ? customRoleFromRow(row) : null;
    if (!role) throw new CustomRoleError("Не удалось сохранить роль.", 500, "ROLE_SAVE_FAILED");
    return role;
  } catch (error) {
    if (error && typeof error === "object" && "code" in error && error.code === "23505") throw new CustomRoleError("Роль с таким названием уже существует.", 409, "ROLE_NAME_EXISTS");
    throw error;
  }
}
