import { getDatabase, type PostgresDatabase } from "../db/client";
import { accessibleProjectIds, defaultProjectAccess, isUserRole, type ProjectAccess, type ProjectAccessUser, type UserRole } from "./roles.ts";

type Executor = Pick<PostgresDatabase, "prepare" | "batch">;
type ProjectUser = { id: number; role: UserRole; assignedSiteId?: number | null; customRoleId?: number | null };
export type UserProjectAccessSettings = { projectAccess: ProjectAccess; canViewPendingReports: boolean };
export type UserProjectAccessInput = { projectAccess?: unknown; canViewPendingReports?: unknown };

export function canManageUserProjectAccess(actor: ProjectAccessUser, target: ProjectAccess) {
  const allowed = accessibleProjectIds(actor);
  return allowed === null || target.mode === "selected" && target.siteIds.every(id => allowed.includes(id));
}
const schemaTasks = new WeakMap<PostgresDatabase, Promise<void>>();

export async function ensureUserProjectAccessSchema(db = getDatabase()) {
  if (process.env.NODE_ENV === "production" && process.env.DATABASE_RUNTIME_BOOTSTRAP !== "true") return;
  let task = schemaTasks.get(db);
  if (!task) {
    task = db.transaction(async tx => {
      // Authentication can bootstrap before the application's first data load.
      await tx.prepare(`CREATE TABLE IF NOT EXISTS sites (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL,
        code TEXT NOT NULL UNIQUE, timezone TEXT NOT NULL DEFAULT 'Europe/Moscow', active INTEGER NOT NULL DEFAULT 1
      )`).run();
      await tx.prepare(`CREATE TABLE IF NOT EXISTS user_project_access (
        user_id INTEGER PRIMARY KEY REFERENCES app_users(id) ON DELETE CASCADE,
        all_projects INTEGER NOT NULL DEFAULT 0 CHECK (all_projects IN (0, 1)),
        can_view_pending_reports INTEGER NOT NULL DEFAULT 0 CHECK (can_view_pending_reports IN (0, 1)),
        updated_by_user_id INTEGER REFERENCES app_users(id) ON DELETE SET NULL,
        updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
      )`).run();
      await tx.prepare(`CREATE TABLE IF NOT EXISTS user_project_access_sites (
        user_id INTEGER NOT NULL REFERENCES user_project_access(user_id) ON DELETE CASCADE,
        site_id INTEGER NOT NULL REFERENCES sites(id) ON DELETE CASCADE,
        PRIMARY KEY (user_id, site_id)
      )`).run();
      await tx.prepare("CREATE INDEX IF NOT EXISTS idx_user_project_access_sites_site ON user_project_access_sites(site_id, user_id)").run();
      // The removed role had the engineer's working rights across all projects.
      await tx.prepare(`INSERT INTO user_project_access(user_id, all_projects, can_view_pending_reports)
        SELECT id, 1, 1 FROM app_users WHERE role = 'admin' ON CONFLICT (user_id) DO NOTHING`).all();
      await tx.prepare("UPDATE app_users SET role = 'engineer' WHERE role = 'admin'").run();
    }).catch(error => { schemaTasks.delete(db); throw error; });
    schemaTasks.set(db, task);
  }
  await task;
}

export function normalizeProjectAccess(input: unknown): ProjectAccess {
  if (!input || typeof input !== "object" || Array.isArray(input)) throw new Error("Укажите доступ к проектам.");
  const value = input as { mode?: unknown; siteIds?: unknown };
  if (value.mode === "all") return { mode: "all", siteIds: [] };
  if (value.mode !== "selected" || !Array.isArray(value.siteIds) || value.siteIds.length > 10000
    || value.siteIds.some(id => typeof id !== "number" || !Number.isSafeInteger(id) || id < 1 || id > 2147483647)) {
    throw new Error("Выберите действующие проекты из списка.");
  }
  return { mode: "selected", siteIds: [...new Set(value.siteIds as number[])].sort((a, b) => a - b) };
}

export async function loadUserProjectAccess(user: ProjectUser, executor: Executor = getDatabase()): Promise<UserProjectAccessSettings> {
  const saved = await executor.prepare(`SELECT all_projects AS allProjects, can_view_pending_reports AS canViewPendingReports
    FROM user_project_access WHERE user_id = ?`).bind(user.id).first<{ allProjects: number | boolean; canViewPendingReports: number | boolean }>();
  if (user.role === "superadmin") return { projectAccess: { mode: "all", siteIds: [] }, canViewPendingReports: true };
  if (!saved) return { projectAccess: defaultProjectAccess(user.role, user.assignedSiteId, user.customRoleId), canViewPendingReports: user.role !== "viewer" };
  const projects = saved.allProjects ? [] : (await executor.prepare(`SELECT access.site_id AS id FROM user_project_access_sites access
    JOIN sites site ON site.id = access.site_id WHERE access.user_id = ? AND site.active = 1 ORDER BY access.site_id`).bind(user.id).all<{ id: number }>()).results.map(row => row.id);
  return { projectAccess: { mode: saved.allProjects ? "all" : "selected", siteIds: projects },
    canViewPendingReports: user.role !== "viewer" || Boolean(saved.canViewPendingReports) };
}

/** Pass a transaction executor to save project access together with roles/permissions. */
export async function saveUserProjectAccess(userId: number, input: UserProjectAccessInput, updatedByUserId: number, executor?: Executor): Promise<UserProjectAccessSettings> {
  await ensureUserProjectAccessSchema();
  const persist = async (db: Executor) => {
    const user = await db.prepare(`SELECT id, CASE WHEN role = 'admin' THEN 'engineer' WHEN role = 'office' THEN 'superadmin' ELSE role END AS role,
      assigned_site_id AS assignedSiteId, custom_role_id AS customRoleId FROM app_users WHERE id = ? AND active = 1 FOR UPDATE`).bind(userId).first<ProjectUser>();
    if (!user || !isUserRole(user.role)) throw new Error("Пользователь не найден.");
    const previous = await loadUserProjectAccess(user, db);
    const projectAccess = user.role === "superadmin" ? { mode: "all" as const, siteIds: [] }
      : input.projectAccess === undefined ? previous.projectAccess : normalizeProjectAccess(input.projectAccess);
    if (input.canViewPendingReports !== undefined && typeof input.canViewPendingReports !== "boolean") throw new Error("Укажите доступ к черновикам и отчётам на проверке.");
    if (projectAccess.mode === "selected" && projectAccess.siteIds.length) {
      const sites = await db.prepare("SELECT id FROM sites WHERE id = ANY(?::integer[]) AND active = 1 FOR SHARE").bind(projectAccess.siteIds).all<{ id: number }>();
      if (sites.results.length !== projectAccess.siteIds.length) throw new Error("Один из выбранных проектов не найден или архивирован. Обновите список проектов.");
    }
    const canViewPendingReports = user.role !== "viewer" ? true : input.canViewPendingReports === undefined ? previous.canViewPendingReports : input.canViewPendingReports as boolean;
    await db.prepare(`INSERT INTO user_project_access (user_id, all_projects, can_view_pending_reports, updated_by_user_id, updated_at)
      VALUES (?, ?, ?, ?, CURRENT_TIMESTAMP) ON CONFLICT(user_id) DO UPDATE SET all_projects = EXCLUDED.all_projects,
        can_view_pending_reports = EXCLUDED.can_view_pending_reports, updated_by_user_id = EXCLUDED.updated_by_user_id, updated_at = CURRENT_TIMESTAMP`)
      .bind(userId, projectAccess.mode === "all" ? 1 : 0, canViewPendingReports ? 1 : 0, updatedByUserId).all();
    await db.prepare("DELETE FROM user_project_access_sites WHERE user_id = ?").bind(userId).run();
    for (const siteId of projectAccess.siteIds) await db.prepare("INSERT INTO user_project_access_sites(user_id, site_id) VALUES (?, ?)").bind(userId, siteId).all();
    return { projectAccess, canViewPendingReports };
  };
  return executor ? persist(executor) : getDatabase().transaction(persist);
}
