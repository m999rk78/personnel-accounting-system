import { getDatabase, type PostgresDatabase } from "../db/client";
import { randomUUID } from "node:crypto";
import { CustomRoleError, customRoleNameKey, inferCustomRoleBaseRole, inheritedCustomRoleStatusPermissions, managedDefaultRoleSeeds, normalizeCustomRoleInput, normalizeCustomRoleName, normalizeCustomRolePermissions, type CustomRole, type CustomRoleInput } from "./customRoles.ts";

type Executor = Pick<PostgresDatabase, "prepare">;
const schemaTasks = new WeakMap<PostgresDatabase, Promise<void>>();

export async function ensureCustomRolesSchema(db?: PostgresDatabase) {
  if (process.env.NODE_ENV === "production" && process.env.DATABASE_RUNTIME_BOOTSTRAP !== "true") return;
  const database = db ?? getDatabase();
  let task = schemaTasks.get(database);
  if (!task) {
    task = (async () => {
      const { ensureUserProjectAccessSchema } = await import("./projectAccessServer.ts");
      await ensureUserProjectAccessSchema(database);
      return database.transaction(async tx => {
      await tx.prepare(`CREATE TABLE IF NOT EXISTS custom_roles (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL, name_key TEXT NOT NULL UNIQUE,
        base_role TEXT NOT NULL CHECK (base_role IN ('foreman', 'engineer', 'viewer')),
        permissions JSONB NOT NULL CHECK (jsonb_typeof(permissions) = 'object'),
        revision INTEGER NOT NULL DEFAULT 1 CHECK (revision > 0),
        active INTEGER NOT NULL DEFAULT 1 CHECK (active IN (0, 1)),
        created_by_user_id INTEGER REFERENCES app_users(id) ON DELETE SET NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
        updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
      )`).run();
      await tx.prepare("ALTER TABLE app_users ADD COLUMN IF NOT EXISTS custom_role_id INTEGER REFERENCES custom_roles(id) ON DELETE RESTRICT").run();
      await tx.prepare("CREATE INDEX IF NOT EXISTS idx_app_users_custom_role ON app_users(custom_role_id)").run();
      await tx.prepare("ALTER TABLE custom_roles ADD COLUMN IF NOT EXISTS legacy_role_key TEXT").run();
      await tx.prepare("CREATE UNIQUE INDEX IF NOT EXISTS idx_custom_roles_legacy_key ON custom_roles(legacy_role_key)").run();
      await tx.prepare("ALTER TABLE custom_roles DROP CONSTRAINT IF EXISTS custom_roles_base_role_check").run();
      await tx.prepare("ALTER TABLE custom_roles ADD CONSTRAINT custom_roles_base_role_check CHECK(base_role IN ('foreman','engineer','viewer'))").run();
      for (const seed of managedDefaultRoleSeeds()) await tx.prepare(`INSERT INTO custom_roles(name,name_key,base_role,permissions,legacy_role_key)
        VALUES(?,?,?,?::jsonb,?) ON CONFLICT(legacy_role_key) DO NOTHING`).bind(seed.name, customRoleNameKey(seed.name), seed.key, JSON.stringify(seed.permissions), seed.key).all();
      await tx.prepare(`WITH inserted AS (
        INSERT INTO user_project_access(user_id,all_projects,can_view_pending_reports)
        SELECT id,CASE WHEN role='engineer' THEN 1 ELSE 0 END,CASE WHEN role='viewer' THEN 0 ELSE 1 END
        FROM app_users WHERE custom_role_id IS NULL AND role IN ('foreman','engineer','viewer')
        ON CONFLICT(user_id) DO NOTHING RETURNING user_id
      ) INSERT INTO user_project_access_sites(user_id,site_id)
        SELECT u.id,u.assigned_site_id FROM app_users u JOIN inserted i ON i.user_id=u.id
        JOIN sites s ON s.id=u.assigned_site_id AND s.active=1 WHERE u.role='foreman'
        ON CONFLICT DO NOTHING`).all();
      await tx.prepare(`UPDATE app_users u SET custom_role_id=r.id FROM custom_roles r
        WHERE u.custom_role_id IS NULL AND u.role=r.legacy_role_key AND r.active=1`).run();
      });
    })().catch(error => { schemaTasks.delete(database); throw error; });
    schemaTasks.set(database, task);
  }
  await task;
}

type CustomRoleRow = { id: number; name: string; baseRole: string; permissions: unknown; revision: number; legacyRoleKey?: CustomRole["legacyRoleKey"] };
function customRoleFromRow(row: CustomRoleRow): CustomRole | null {
  try {
    const original = typeof row.permissions === "string" ? JSON.parse(row.permissions) : row.permissions;
    const permissions = normalizeCustomRolePermissions(original, row.baseRole === "foreman" || row.baseRole === "engineer" || row.baseRole === "viewer" ? row.baseRole : undefined);
    const inheritedStatusPermissions = inheritedCustomRoleStatusPermissions(original);
    const baseRole = row.baseRole === "foreman" ? "foreman" : inferCustomRoleBaseRole(permissions);
    if (baseRole !== row.baseRole || !Number.isSafeInteger(row.id) || row.id < 1 || !Number.isSafeInteger(row.revision) || row.revision < 1) return null;
    return { id: row.id, name: normalizeCustomRoleName(row.name), baseRole, permissions, revision: row.revision, ...(row.legacyRoleKey ? { legacyRoleKey: row.legacyRoleKey } : {}), ...(inheritedStatusPermissions.length ? { inheritedStatusPermissions } : {}) };
  } catch { return null; }
}
const columns = "id, name, base_role AS baseRole, permissions, revision, legacy_role_key AS legacyRoleKey";

export async function listCustomRoles(executor: Executor = getDatabase()): Promise<CustomRole[]> {
  await ensureCustomRolesSchema();
  const result = await executor.prepare(`SELECT ${columns} FROM custom_roles WHERE active = 1 ORDER BY name_key, id`).all<CustomRoleRow>();
  return result.results.flatMap(row => { const role = customRoleFromRow(row); return role ? [role] : []; });
}

export async function loadCustomRole(id: number, executor: Executor = getDatabase()): Promise<CustomRole | null> {
  if (!Number.isSafeInteger(id) || id < 1 || id > 2147483647) return null;
  await ensureCustomRolesSchema();
  const row = await executor.prepare(`SELECT ${columns} FROM custom_roles WHERE id = ? AND active = 1`).bind(id).first<CustomRoleRow>();
  return row ? customRoleFromRow(row) : null;
}

export async function createCustomRole(input: CustomRoleInput, actorId: number, executor: Executor = getDatabase()): Promise<CustomRole> {
  const normalized = normalizeCustomRoleInput(input);
  await ensureCustomRolesSchema();
  try {
    const row = await executor.prepare(`INSERT INTO custom_roles(name, name_key, base_role, permissions, created_by_user_id)
      VALUES (?, ?, ?, ?::jsonb, ?) RETURNING ${columns}`)
      .bind(normalized.name, customRoleNameKey(normalized.name), normalized.baseRole, JSON.stringify(normalized.permissions), actorId).first<CustomRoleRow>();
    const role = row ? customRoleFromRow(row) : null;
    if (!role) throw new CustomRoleError("Не удалось сохранить роль.", 500, "ROLE_SAVE_FAILED");
    return role;
  } catch (error) {
    if (error && typeof error === "object" && "code" in error && error.code === "23505") throw new CustomRoleError("Роль с таким названием уже существует.", 409, "ROLE_NAME_EXISTS");
    throw error;
  }
}

function roleIdentity(id: unknown, revision: unknown) {
  if (!Number.isSafeInteger(id) || Number(id) < 1 || Number(id) > 2147483647 || !Number.isSafeInteger(revision) || Number(revision) < 1) throw new CustomRoleError("Обновите справочник и выберите роль заново.");
  return { id: Number(id), revision: Number(revision) };
}

export async function updateCustomRole(input: CustomRoleInput & { id?: unknown; revision?: unknown }, database: PostgresDatabase = getDatabase()): Promise<CustomRole> {
  const identity = roleIdentity(input.id, input.revision);
  const normalized = normalizeCustomRoleInput(input);
  await ensureCustomRolesSchema(database);
  try {
    return await database.transaction(async db => {
      // User assignment and role changes share a lock: no user can acquire a
      // stale base role, or be assigned while the template is being archived.
      await db.prepare("SELECT pg_advisory_xact_lock(hashtext(?))").bind("user-role-management").first();
      const current = await db.prepare(`SELECT ${columns} FROM custom_roles WHERE id = ? AND active = 1 FOR UPDATE`).bind(identity.id).first<CustomRoleRow>();
      if (!current) throw new CustomRoleError("Роль не найдена.", 404, "ROLE_NOT_FOUND");
      if (current.revision !== identity.revision) throw new CustomRoleError("Роль уже изменена другим пользователем. Обновите справочник.", 409, "ROLE_REVISION_CONFLICT");
      const baseRole = current.baseRole === "foreman" ? "foreman" : normalized.baseRole;
      const row = await db.prepare(`UPDATE custom_roles SET name = ?, name_key = ?, base_role = ?, permissions = ?::jsonb,
        revision = revision + 1, updated_at = CURRENT_TIMESTAMP WHERE id = ? AND revision = ? AND active = 1 RETURNING ${columns}`)
        .bind(normalized.name, normalized.nameKey, baseRole, JSON.stringify(normalized.permissions), identity.id, identity.revision).first<CustomRoleRow>();
      const role = row ? customRoleFromRow(row) : null;
      if (!role) throw new CustomRoleError("Не удалось сохранить роль.", 409, "ROLE_REVISION_CONFLICT");
      // Auth checks that a user's base role agrees with their custom template.
      // Keep both in sync atomically, including when the last write permission is removed.
      if (current.baseRole !== role.baseRole) await db.prepare("UPDATE app_users SET role = ? WHERE custom_role_id = ?").bind(role.baseRole, role.id).run();
      return role;
    });
  } catch (error) {
    if (error && typeof error === "object" && "code" in error && error.code === "23505") throw new CustomRoleError("Роль с таким названием уже существует.", 409, "ROLE_NAME_EXISTS");
    throw error;
  }
}

export async function deleteCustomRole(id: unknown, revision: unknown, database: PostgresDatabase = getDatabase()) {
  const identity = roleIdentity(id, revision);
  await ensureCustomRolesSchema(database);
  return database.transaction(async db => {
    await db.prepare("SELECT pg_advisory_xact_lock(hashtext(?))").bind("user-role-management").first();
    const role = await db.prepare(`SELECT ${columns} FROM custom_roles WHERE id = ? AND active = 1 FOR UPDATE`).bind(identity.id).first<CustomRoleRow>();
    if (!role) throw new CustomRoleError("Роль не найдена.", 404, "ROLE_NOT_FOUND");
    if (role.revision !== identity.revision) throw new CustomRoleError("Роль уже изменена. Обновите справочник.", 409, "ROLE_REVISION_CONFLICT");
    const users = await db.prepare("SELECT COUNT(*) AS count FROM app_users WHERE custom_role_id = ? AND active = 1").bind(identity.id).first<{ count: number }>();
    if (Number(users?.count ?? 0) > 0) throw new CustomRoleError(`Эта роль назначена пользователям (${users!.count}). Сначала назначьте им другую роль.`, 409, "ROLE_IN_USE");
    await db.prepare("UPDATE custom_roles SET active = 0, name_key = ?, revision = revision + 1, updated_at = CURRENT_TIMESTAMP WHERE id = ? AND active = 1")
      .bind(`__archived_role:${identity.id}:${randomUUID()}`, identity.id).run();
    return { id: identity.id, name: role.name };
  });
}
